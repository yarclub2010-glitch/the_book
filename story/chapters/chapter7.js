// Глава 7. «Лампа для ногтей» — загадка 6 (docs/загадки.md). Акт 3: находка причины раскола.
//
// Тихон из мира «Не приходи» всё ещё в мире «Приходи». Вера на смене до девяти.
// Двойник (в мире «Не приходи») увидел сторис тамошней Веры-реставратора: железо-галловые
// чернила после воды проступают в ультрафиолете. Он прожигает это в книге — сюда доходят
// обрывки (закон 4): «…записк… …в столе… …ультраф…», и только когда у книги никого (закон 3).
// Записка есть только в этом мире (закон 2) — в ящике стола двойника.
// Реставрационной УФ-лампы здесь нет: Вера всё выбросила. Зато у неё есть лампа для ногтей.
// Взять её, пока Вера не вернулась, и просветить записку: «Не приходи провожать».

const HERE = ['kitchen', 'book'];

export default {
  id: 'ch7',
  title: 'Глава 7. Лампа для ногтей',
  hero: 't',
  chars: {
    t: { name: 'Тихон', world: 'np' },
    v: { name: 'Вера', world: 'p' },
    m: { name: 'Мама', world: 'p' },
  },

  start: { location: 'room', time: 'evening' },

  locations: {
    room: { name: 'Его комната', scene: () => 'room-p', music: () => 'p-night' },
    hall: { name: 'Коридор', scene: () => 'hall-p', music: () => 'p-night' },
    kitchen: { name: 'Кухня', scene: () => 'kitchen-p-evening', music: () => 'p-night' },
    vera: { name: 'Комната Веры', scene: () => 'vera-p', music: () => 'p-night' },
    book: { name: 'Книга', hidden: true, scene: () => 'book-p', music: () => 'p-night' },
    note: { name: 'Записка', hidden: true, scene: () => 'note-p', music: () => 'p-night' },
  },

  sceneClasses: (s) => [
    'w-hint-on',
    s.flags.msg && 'w-p7-on',
    s.flags.uv && 'uv-on',
  ].filter(Boolean),

  carry: (s) => (s.flags.hasLamp ? 'Верина лампа для ногтей' : ''),

  // развилка: показал записку сам (ветка «Обмен») или оставил разговор двойнику (главы 8–9)
  remember: (s) => ({ choice: s.flags.choice }),
  next: (s) => (s.flags.choice === 'show' ? 'ch8x' : 'ch8'),

  end: {
    text: (s) => (s.flags.choice === 'show'
      ? ['Вера узнала правду. Но услышала её не от того брата.', 'Двойник по ту сторону этого не знает. Пока.']
      : ['В ультрафиолете проступило одно слово. Тихон спрятал его обратно.', 'Сказать его Вере должен тот, чья это жизнь.']),
  },

  intro: [
    ['card', '18:30', 'Вера дома', 'p'],
    ['think', 'Его комната. Паяльник, провода, доска с «уликами» против меня.'],
    ['think', 'Вера на смене до девяти. Вечером она хочет говорить про вокзал.'],
    ['think', 'А я даже не знаю, что было на этом вокзале.'],
  ],

  interact(scene, id, s) {
    const f = s.flags;

    if (scene === 'hall-p') {
      if (id === 'corridor') return { go: 'kitchen' };
      if (id === 'vera') return { go: 'vera' };
    }
    if (scene === 'kitchen-p-evening') {
      if (id === 'book') return { go: 'book' };
      if (id === 'sink') return { key: 'ch7', lines: ['Хлебница. Сегодня в ней хлеб. Настоящий. Вера всё-таки купила.'] };
    }

    if (scene === 'book-p') {
      if (id === 'marginL' || id === 'pageL') {
        if (f.msg) return { key: 'msg', set: { readMsg: true }, lines: ['«…записк… …в столе… …ультраф…» Три обрывка, три ожога.', 'Записка. В его столе. Ультрафиолет?'] };
        return { key: 'old', lines: ['«…наушн… …хлеб…» — утреннее. Больше ничего.'] };
      }
    }

    if (scene === 'room-p') {
      if (id === 'drawer') return { go: 'note' };
    }

    if (scene === 'vera-p') {
      if (id === 'naillamp') {
        if (!f.hasLamp) return { key: 'take', set: { hasLamp: true }, lines: ['Белая лампа-купол, внутри — ряд синеватых диодов, наклейка «UV». Вера сушит под ней лак.', 'Вера на работе. Возьму на минутку. Верну — она и не заметит.'] };
        return { key: 'taken', lines: ['На столе — светлый круг, где стояла лампа. Вернуть до девяти.'] };
      }
    }

    if (scene === 'note-p' && id === 'note') {
      if (f.uv) return { key: 'uv', lines: ['«Не приходи провожать». Тёмным по светящейся бумаге.'] };
      if (f.hasLamp) {
        return {
          beat: [
            ['think', 'Ставлю лампу над листом. Щелчок.'],
            ['sfx', 'ui'],
            ['set', { uv: true }],
            ['wait', 2.2],
            ['sfx', 'sting'],
            ['think', 'Бумага светится голубым. А чернила — наоборот, темнеют.'],
            ['think', 'И там, где было пятно…'],
            ['say', 't', '«Не».'],
            ['say', 't', '«Не приходи провожать».'],
            ['think', 'Здесь дождь стёр одно слово — и здешний я побежал на вокзал.'],
            ['think', 'Вот он, их вокзал. Он шесть лет уверен, что его позвали. Она шесть лет уверена, что он её предал.'],
            ['think', 'А я знал это слово всю жизнь. Только в своём мире — там, где оно ничего не спасло.'],
            ['music', null, { fade: 2 }],
            ['sfx', 'door', { caption: 'хлопнула входная дверь' }], ['sfx', 'steps'],
            ['say', 'v', 'Тиш, я дома! Отпустили пораньше.'],
            ['say', 'v', '…Тиш? Это моя лампа? Что ты там светишь?'],
            ['think', 'Записка у меня в руках. Слово проступило. Она стоит в дверях.'],
            ['think', 'Это не мой разговор. Это его сестра, его вокзал, его шесть лет.'],
            ['think', 'Но он — там. А она — здесь.'],
            ['choice', [
              {
                text: 'Показать ей записку',
                do: [
                  ['set', { choice: 'show' }],
                  ['music', 'vera', { fade: 2 }],
                  ['say', 't', 'Вер. Смотри.'],
                  ['narr', 'Вера наклоняется над лампой. Долго молчит.'],
                  ['say', 'v', '«Не»… Я же писала «не». Я помню, как писала.'],
                  ['say', 'v', 'Там было пятно? Всё это время — просто пятно?'],
                  ['say', 'v', 'Тиш… ты не назло. Ты просто не смог прочесть.'],
                  ['narr', 'Она обнимает брата. Не того брата.'],
                  ['think', 'Шесть лет она ждала этих слов. Их сказал не он.'],
                  ['card', 'Не', 'Правда дошла. Не от того, кто должен был её сказать'],
                  ['end'],
                ],
              },
              {
                text: 'Спрятать записку и вернуть лампу',
                do: [
                  ['set', { choice: 'hide' }],
                  ['sfx', 'ui'],
                  ['say', 't', 'Ничего. Хотел посмотреть, как она работает. Прости.'],
                  ['say', 'v', 'Ты вечно всё разбираешь. Поставь на место, ладно?'],
                  ['think', 'Ставлю лампу на её стол. Записку — обратно в ящик.'],
                  ['think', 'Он должен сказать ей сам. Своими словами. Иначе это ничего не исправит.'],
                  ['card', 'Не', 'Слово найдено. Сказать его должен другой'],
                  ['end'],
                ],
              },
            ]],
          ],
        };
      }
      return { key: 'day', lines: ['«Тиша, поезд в 6:40. … приходи провожать — мама проснётся. Я напишу. В.»', 'Я знаю эту записку. Я читал её шесть лет назад — в своём мире. Там первое слово было целым.', 'А здесь на его месте — пятно. Будто капля упала прямо на него.'] };
    }
    return null;
  },

  timers: [
    {
      // закон 3: послание двойника доходит, когда у книги никого
      id: 'msg',
      after: 25,
      once: true,
      when: (s) => !HERE.includes(s.location),
      set: { msg: true },
      do: [['sfx', 'page', { caption: 'на кухне шелестит бумага' }], ['wait', 0.8], ['thought', 'Из кухни потянуло палёной бумагой. Он опять что-то написал.']],
    },
    {
      id: 'lamp-hint',
      after: 60,
      once: true,
      when: (s) => s.flags.readMsg && !s.flags.hasLamp,
      do: [['thought', 'Ультрафиолет. У той Веры — целая мастерская. А у этой что вообще светит фиолетовым?']],
    },
    {
      id: 'train',
      every: [35, 60],
      when: (s) => ['room', 'hall', 'kitchen', 'vera'].includes(s.location),
      do: [['sfx', 'train', { caption: 'идёт электричка', dur: 5 }], ['event', 'train'], ['shake', 2]],
    },
  ],

  rules: [],
};
