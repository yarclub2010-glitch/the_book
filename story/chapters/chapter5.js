// Глава 5. «Сойти за своего» — загадка 5, половина А (docs/загадки.md). Акт 2–3: первый обмен.
//
// Тихон из мира «Не приходи» проснулся в чужой жизни — в мире «Приходи». Вера здесь, живая,
// и ей срочно нужны наушники: «Ты обещал починить к вечеру». Где они — знает только двойник.
// Двойник (теперь в мире «Не приходи») прожигает подсказку в своей книге; сюда доходят обрывки
// (закон 4): «…наушн… …хлеб…» — и только когда рядом с книгой никого нет (закон 3).
// Разгадка: весь первый акт «призрак» прятал мелочи в хлебницу — это привычка двойника.
// Наушники — в хлебнице, уже починенные.

const HERE = ['kitchen', 'book', 'bread'];

export default {
  id: 'ch5',
  title: 'Глава 5. Сойти за своего',
  hero: 't',
  next: 'ch6',
  chars: {
    t: { name: 'Тихон', world: 'np' },
    v: { name: 'Вера', world: 'p' },
    m: { name: 'Мама', world: 'p' },
  },

  start: { location: 'hall', time: 'morning' },

  locations: {
    hall: { name: 'Коридор', scene: () => 'hall-p', music: () => 'p-night' },
    kitchen: { name: 'Кухня', scene: () => 'kitchen-p-evening', music: () => 'p-night' },
    room: { name: 'Его комната', scene: () => 'room-p', music: () => 'p-night' },
    vera: { name: 'Комната Веры', scene: () => 'vera-p', music: () => 'p-night' },
    bread: { name: 'Хлебница', hidden: true, scene: () => 'bread-p', music: () => 'p-night' },
    book: { name: 'Книга', hidden: true, scene: () => 'book-p', music: () => 'p-night' },
  },

  sceneClasses: (s) => [
    !s.flags.given && 'vera-here',
    s.flags.breadOpen && 'bread-open',
    s.flags.hint && 'w-hint-on',
  ].filter(Boolean),

  carry: (s) => (s.flags.hasHeadphones && !s.flags.given ? 'Верины наушники' : ''),

  end: {
    text: [
      'Тихон прошёл первое испытание чужой жизнью: вернул Вере наушники, которые чинил не он.',
      'Вечером она хочет поговорить. Про вокзал. Про ночь, которой в его мире не было.',
    ],
  },

  intro: [
    ['card', '6:41', 'Чужая водолазка на стуле', 'p'],
    ['say', 'v', 'Тиш, ты чего в такую рань? И почему в водолазке — ты ж их не носишь.'],
    ['choice', [
      { text: 'Замёрз.', do: [['say', 'v', 'В сентябре? Ну-ну.']] },
      { text: 'Не спалось.', do: [['say', 'v', 'Тебе вечно не спится. Ладно.']] },
    ]],
    ['say', 'v', 'Наушники мои где? Обещал починить к вечеру. У меня смена до девяти, в читалке тишина — я без музыки там умру.'],
    ['think', 'Наушники. «Обещал починить». Значит, он ещё и чинит. И где-то это держит.'],
    ['say', 'v', 'Через двадцать минут выхожу. Не найдёшь — ну и ладно, как всегда.'],
  ],

  interact(scene, id, s) {
    const f = s.flags;

    // ---------- коридор ----------
    if (scene === 'hall-p') {
      if (id === 'corridor') return { go: 'kitchen' };
      if (id === 'vera') {
        if (f.given) return { key: 'after', lines: ['Её дверь приоткрыта. Она напевает под нос — шесть нот. Я их откуда-то знаю.'] };
        if (f.hasHeadphones) {
          return {
            beat: [
              ['music', 'vera', { fade: 2 }],
              ['say', 't', 'Вот. Твои.'],
              ['say', 'v', 'О! Работают… Спасибо, Тиш.'],
              ['set', { given: true }],
              ['say', 'v', 'Ты сегодня какой-то… нормальный. Даже не огрызаешься.'],
              ['think', 'Шесть лет я слышал её голос только из сторис. А она не знает, что я — не он.'],
              ['say', 'v', 'Вечером поговорим? Про… ну, про тот вокзал. Если захочешь.'],
              ['think', 'Вокзал? В моём мире я туда не ходил.'],
              ['music', null, { fade: 2 }],
              ['sfx', 'sting'],
              ['card', 'Вокзал', 'Что было в ту ночь в этом мире?'],
              ['end'],
            ],
          };
        }
        return { key: 'ask', lines: ['«Ну что, нашёл?» Она смотрит так, будто заранее знает ответ.', 'Стоит в дверях и ждёт. Как будто я всегда её подводил.'] };
      }
      return null;
    }

    // ---------- кухня ----------
    if (scene === 'kitchen-p-evening') {
      if (id === 'book') return { go: 'book' };
      if (id === 'sink') return { go: 'bread' };
      if (id === 'fridge') return { key: 'ch5', lines: ['«УХОДИ» на холодильнике. Крупно, ровно. Это мне. А я стою у его холодильника, в его доме.'] };
      if (id === 'photo') return { key: 'ch5', lines: ['То самое фото. Здесь оно такое же. Единственное, что здесь такое же.'] };
    }

    // ---------- книга ----------
    if (scene === 'book-p') {
      const hint = { key: 'hint', set: { readHint: true }, lines: ['«…наушн… …хлеб…» Коричневым, едва-едва, под текстом. Он пишет мне оттуда.', 'Наушники — и хлеб? При чём тут хлеб?'] };
      const mine = { key: 'r', lines: ['«Кто ты?» на полях — мой ожог. Здесь он бледный, как старый синяк. Но дошёл.'] };
      if (id === 'pageL') return f.hint ? hint : { key: 'wait', lines: ['Страницы волнами, в рыжих разводах — как будто книгу когда-то забыли под дождём. Пока пусто.'] };
      if (id === 'marginL') return mine;
      if (id === 'pageR') return mine;
    }

    // ---------- хлебница ----------
    if (scene === 'bread-p' && id === 'breadbox') {
      if (!f.breadOpen) {
        return {
          key: 'open',
          set: { breadOpen: true, hasHeadphones: true },
          lines: ['Хлеба в хлебнице нет. Зато — батарейки, ключи… и наушники. Дужка обмотана синей изолентой.', 'Починены. Он всё прячет в хлебницу. А у нас мама потом выгребает оттуда батарейки и ругается на меня.'],
        };
      }
      return { key: 'empty', lines: ['Батарейки, ключи, моток изоленты. Хлеба нет. Теперь ясно, почему Вера пишет «Купи хлеб!!».'] };
    }

    return null;
  },

  timers: [
    {
      // закон 3: подсказка двойника доходит, когда рядом с книгой никого нет
      id: 'hint',
      after: 25,
      once: true,
      when: (s) => !HERE.includes(s.location),
      set: { hint: true },
      do: [['sfx', 'page', { caption: 'на кухне шелестит бумага' }], ['wait', 0.8], ['thought', 'Запахло палёной бумагой. Из кухни.']],
    },
    {
      id: 'hurry1',
      after: 70,
      once: true,
      when: (s) => !s.flags.hasHeadphones,
      do: [['sfx', 'steps', { caption: 'Вера из коридора: «Тиш, десять минут!»' }]],
    },
    {
      id: 'hurry2',
      after: 150,
      once: true,
      when: (s) => !s.flags.hasHeadphones,
      do: [['sfx', 'steps', { caption: 'Вера: «Всё, я почти одета!»' }], ['wait', 1], ['thought', 'Он чинит — и куда-то прячет. Куда бы спрятал я, если б жил в этом шуме?']],
    },
    {
      id: 'train',
      every: [35, 60],
      when: (s) => ['hall', 'kitchen', 'room', 'vera'].includes(s.location),
      do: [['sfx', 'train', { caption: 'идёт электричка', dur: 5 }], ['event', 'train'], ['shake', 2]],
    },
  ],

  rules: [],
};
